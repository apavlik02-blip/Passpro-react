// Builds the P&C question-bank migration from supabase/content/pc-questions/*.json.
//
// Source format (one object per question):
//   { d: domain, l: difficulty, q: question, o: [correct, ...distractors],
//     x: explanation, k: know_this, s: true if Wisconsin-specific }
//
// The correct answer is always written FIRST in the source files (easy to
// review); this script shuffles options with a seeded RNG so the answer
// position is balanced and stable across rebuilds.
//
// Usage: node supabase/content/build-pc-migration.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const srcDir = join(here, 'pc-questions')
const outFile = join(here, '..', 'migrations', '20260924120000_pc_question_bank.sql')

const VALID_DOMAINS = new Set([
  'pc_regulation', 'wi_pc_statutes', 'wi_property_regulation', 'wi_auto_regulation',
  'pc_general_insurance', 'property_basics', 'casualty_basics', 'dwelling', 'homeowners',
  'commercial_property', 'businessowners_property', 'personal_auto', 'commercial_auto',
  'commercial_liability', 'businessowners_liability', 'workers_comp', 'personal_other',
  'umbrella', 'casualty_other',
])
const VALID_DIFFICULTY = new Set(['easy', 'medium', 'hard'])

function seededRandom(seed) {
  let state = seed >>> 0
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0
    return state / 2 ** 32
  }
}

function hash(text) {
  let h = 2166136261
  for (const ch of text) {
    h ^= ch.codePointAt(0)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

function shuffle(items, rand) {
  const copy = [...items]
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

function sqlText(value) {
  if (value === null || value === undefined) return 'null'
  return `'${String(value).replaceAll("'", "''")}'`
}

const files = readdirSync(srcDir).filter((f) => f.endsWith('.json')).sort()
const questions = files.flatMap((file) =>
  JSON.parse(readFileSync(join(srcDir, file), 'utf8')).map((q) => ({ ...q, file })),
)

const errors = []
const seen = new Set()
const positions = [0, 0, 0, 0]
const perDomain = {}

const rows = questions.map((q, i) => {
  const where = `${q.file} #${i + 1} (${q.q?.slice(0, 50)})`
  if (!VALID_DOMAINS.has(q.d)) errors.push(`${where}: bad domain ${q.d}`)
  if (!VALID_DIFFICULTY.has(q.l)) errors.push(`${where}: bad difficulty ${q.l}`)
  if (!Array.isArray(q.o) || q.o.length !== 4) errors.push(`${where}: needs exactly 4 options`)
  if (new Set(q.o).size !== q.o.length) errors.push(`${where}: duplicate options`)
  if (!q.x || !q.k) errors.push(`${where}: missing explanation or know_this`)
  const key = q.q.trim().toLowerCase()
  if (seen.has(key)) errors.push(`${where}: duplicate question`)
  seen.add(key)

  const correct = q.o[0]
  const options = shuffle(q.o, seededRandom(hash(q.q)))
  positions[options.indexOf(correct)] += 1
  perDomain[q.d] = (perDomain[q.d] ?? 0) + 1

  return `(${sqlText(q.d)}, ${sqlText(q.l)}, ${sqlText(q.q)}, ${sqlText(JSON.stringify(options))}::jsonb, ${sqlText(correct)}, ${sqlText(q.x)}, ${sqlText(q.k)}, ${q.s ? "'Wisconsin'" : 'null'})`
})

if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}

const sql = `-- Property & Casualty question bank for the Wisconsin Property (22-05),
-- Casualty (22-07), and Personal Lines (22-09) exams.
-- GENERATED by supabase/content/build-pc-migration.mjs from
-- supabase/content/pc-questions/*.json. Edit the JSON, then rebuild.
--
-- Every question traces to the PSI outlines (effective July 15, 2022) or to
-- Wisconsin sources cited in docs/WI-OCI-STANDARDS.md (P&C section).
-- Idempotent: skips any question text already present.

insert into public.questions
  (domain, difficulty, question, options, correct, explanation, know_this, state_specific)
select v.domain, v.difficulty, v.question, v.options, v.correct, v.explanation, v.know_this, v.state_specific
from (values
${rows.join(',\n')}
) as v(domain, difficulty, question, options, correct, explanation, know_this, state_specific)
where not exists (
  select 1 from public.questions existing where existing.question = v.question
);
`

writeFileSync(outFile, sql)
console.log(`Wrote ${rows.length} questions to ${outFile}`)
console.log('Answer position balance (A-D):', positions.join(' / '))
console.table(perDomain)
